"""``strandly cli build``: a self-contained CLI wheel for one deployment.

The wheel ``<command>-client`` holds a small launcher package, the profile's client
coordinates (``profile.json``) and copies of ``strandly_cli`` and ``strandly_mcp`` under
``_vendor/``, so it installs from PyPI dependencies alone and two generated CLIs never clash.
Equal inputs produce byte-identical wheels. Standard library only, so release jobs can run it
with ``PYTHONPATH`` and no install: ``python -m strandly_cli.build --profile F --out D``.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import importlib.util
import json
import sys
import zipfile
from pathlib import Path

from strandly_cli import __version__
from strandly_cli.profile import ClientProfile, ProfileError, load_client_profile

REQUIRES_PYTHON = ">=3.10"
REQUIRES = ("mcp<3", "agent-client-protocol==1.0.0", "httpx<1,>=0.27")
AWS_EXTRA = ("boto3",)
VENDORED = ("strandly_cli", "strandly_mcp")
_ZIP_TIME = (1980, 1, 1, 0, 0, 0)

LAUNCHER = '''"""{display} command-line client, generated by `strandly cli build`. Do not edit."""

from __future__ import annotations

import json
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent


def main() -> int:
    # The vendored client is private to this CLI; it shadows any other installed copy.
    sys.path.insert(0, str(_HERE / "_vendor"))
    from strandly_cli.commands import main as run
    from strandly_cli.profile import ClientProfile

    profile = ClientProfile.from_dict(json.loads((_HERE / "profile.json").read_text(encoding="utf-8")))
    return run(profile=profile)


if __name__ == "__main__":
    sys.exit(main())
'''


def package_name(command: str) -> str:
    return command.replace("-", "_") + "_client"


def distribution_name(command: str) -> str:
    return f"{command}-client"


def _package_dir(name: str) -> Path:
    spec = importlib.util.find_spec(name)
    if spec is None or not spec.submodule_search_locations:
        raise ProfileError(f"cannot find the {name} package to vendor")
    return Path(next(iter(spec.submodule_search_locations)))


def _session_primitives() -> bytes:
    """``strandly_mcp`` vendors ``strandly.core.session_ids`` at build time; prefer that source."""
    vendored = _package_dir("strandly_mcp") / "_session_primitives.py"
    # find_spec on a top-level name locates the package without importing the harness.
    spec = importlib.util.find_spec("strandly")
    if spec is not None and spec.submodule_search_locations:
        canonical = Path(next(iter(spec.submodule_search_locations))) / "core" / "session_ids.py"
        if canonical.is_file():
            return canonical.read_bytes()
    if vendored.is_file():
        return vendored.read_bytes()
    raise ProfileError("cannot find strandly.core.session_ids to vendor")


def _license() -> bytes:
    here = Path(__file__).resolve()
    candidates = [parent / "LICENSE" for parent in list(here.parents)[:4]]
    spec = importlib.util.find_spec("strandly")
    if spec is not None and spec.submodule_search_locations:
        candidates.append(Path(next(iter(spec.submodule_search_locations))) / "_deployment" / "LICENSE")
    for candidate in candidates:
        if candidate.is_file() and b"Apache License" in (data := candidate.read_bytes()):
            return data
    raise ProfileError("cannot find the Apache-2.0 LICENSE to ship in the wheel")


def _vendored_files() -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    for name in VENDORED:
        root = _package_dir(name)
        for path in sorted(root.rglob("*")):
            if path.is_dir() or "__pycache__" in path.parts or path.suffix not in {".py", ".typed"}:
                continue
            files[f"{name}/{path.relative_to(root).as_posix()}"] = path.read_bytes()
    # The coordinates are the profile's, never a value baked into a strandly-mcp release build.
    files["strandly_mcp/_build_info.py"] = b'"""Generated CLI: coordinates come from profile.json."""\n\nPORTAL_URL = None  # type: str | None\n'
    files["strandly_mcp/_session_primitives.py"] = _session_primitives()
    files.pop("strandly_cli/build.py", None)  # a generated CLI does not build CLIs
    return files


def _metadata(profile: ClientProfile) -> str:
    lines = [
        "Metadata-Version: 2.1",
        f"Name: {distribution_name(profile.command)}",
        f"Version: {__version__}",
        f"Summary: {profile.display_name} command-line client (login, chat, sessions, ACP and MCP over stdio)",
        "License: Apache-2.0",
        f"Requires-Python: {REQUIRES_PYTHON}",
        *(f"Requires-Dist: {req}" for req in REQUIRES),
        "Provides-Extra: aws",
        *(f'Requires-Dist: {req}; extra == "aws"' for req in AWS_EXTRA),
    ]
    return "\n".join(lines) + "\n"


def _record_hash(data: bytes) -> str:
    return "sha256=" + base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode("ascii")


def wheel_contents(profile: ClientProfile) -> dict[str, bytes]:
    pkg = package_name(profile.command)
    dist_info = f"{pkg}-{__version__}.dist-info"
    files: dict[str, bytes] = {
        f"{pkg}/__init__.py": f'"""{profile.display_name} client (generated)."""\n'.encode(),
        f"{pkg}/__main__.py": LAUNCHER.format(display=profile.display_name).encode(),
        f"{pkg}/profile.json": (json.dumps(profile.to_dict(), indent=2, sort_keys=True) + "\n").encode(),
    }
    for name, data in _vendored_files().items():
        files[f"{pkg}/_vendor/{name}"] = data
    files[f"{dist_info}/METADATA"] = _metadata(profile).encode()
    files[f"{dist_info}/WHEEL"] = (
        b"Wheel-Version: 1.0\nGenerator: strandly-cli-build\nRoot-Is-Purelib: true\nTag: py3-none-any\n"
    )
    files[f"{dist_info}/entry_points.txt"] = f"[console_scripts]\n{profile.command} = {pkg}.__main__:main\n".encode()
    files[f"{dist_info}/top_level.txt"] = f"{pkg}\n".encode()
    files[f"{dist_info}/licenses/LICENSE"] = _license()
    return files


def build_cli(profile: ClientProfile, out_dir: Path) -> Path:
    """Write ``<out_dir>/<pkg>-<version>-py3-none-any.whl`` and return its path."""
    files = wheel_contents(profile)
    pkg = package_name(profile.command)
    record_name = f"{pkg}-{__version__}.dist-info/RECORD"
    record = "".join(f"{name},{_record_hash(data)},{len(data)}\n" for name, data in sorted(files.items()))
    record += f"{record_name},,\n"
    out_dir.mkdir(parents=True, exist_ok=True)
    wheel = out_dir / f"{pkg}-{__version__}-py3-none-any.whl"
    tmp = wheel.with_suffix(".tmp")
    with zipfile.ZipFile(tmp, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        # Package files first, then the metadata, RECORD last (the wheel convention).
        ordered = sorted(files.items(), key=lambda item: (".dist-info/" in item[0], item[0]))
        for name, data in [*ordered, (record_name, record.encode())]:
            info = zipfile.ZipInfo(name, date_time=_ZIP_TIME)
            info.external_attr = 0o644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(info, data)
    tmp.replace(wheel)
    return wheel


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m strandly_cli.build", description=__doc__.splitlines()[0])
    parser.add_argument("--profile", required=True)
    parser.add_argument("--name")
    parser.add_argument("--out", default="dist")
    args = parser.parse_args(argv)
    try:
        wheel = build_cli(load_client_profile(args.profile, command=args.name), Path(args.out))
    except (ProfileError, OSError) as exc:
        print(f"cli build: {exc}", file=sys.stderr)
        return 1
    print(wheel)
    return 0


if __name__ == "__main__":
    sys.exit(main())
