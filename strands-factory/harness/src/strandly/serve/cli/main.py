"""Command-line entrypoint: ``strands-factory`` (alias ``strandly``). The agent runs deployed
only; these commands deploy, operate and talk to the deployed agent.

Deploy and operate:
- ``provision``                — create the Secrets Manager secret + AgentCore backends.
- ``deploy``                   — deploy the agent runtime (``cdk deploy`` of the AgentRuntime stack).
- ``serve agentcore``          — the deployed runtime's entrypoint.
- ``invoke "<prompt>"``        — fire-and-forget a long task; ``poll <taskId>`` reads it back.
- ``people {list,add,remove}`` — edit the people directory (``ops/people.py``, docs/deploy.md).

Talk to the deployment:
- ``login`` / ``logout``       — browser (PKCE) sign-in for the dashboard API (``~/.strandly/auth.json``);
  ``login`` also verifies who you are with a local GitHub token (``identity``).
- ``chat``                     — chat through the dashboard API; ``--agentcore`` streams over SigV4.
- ``whoami`` / ``identity`` / ``sessions [ID]`` / ``acp`` / ``mcp`` (= ``serve mcp``) — the client commands every
  CLI generated by ``cli build --profile F`` has too (``strandly_cli``).

``invoke``/``poll`` resolve the runtime from ``--runtime-arn`` / ``$STRANDLY_RUNTIME_ARN`` / the
record ``deploy`` wrote to ``~/.strandly/runtime.json``, so they work from any directory.
"""

from __future__ import annotations

import argparse
import logging
import sys
from typing import Any

from strandly_cli import commands as client


def _quiet_noisy_loggers() -> None:
    """Silence library log noise on the interactive surfaces.

    - ``mcp.server.lowlevel`` emits an INFO ``Processing request of type ...`` per call.
    """
    logging.getLogger("mcp.server.lowlevel.server").setLevel(logging.WARNING)


def _deploy_env_keys() -> list[str]:
    """The ``strandly deploy --env`` keys (the AgentRuntime stack's context map; stdlib-only import)."""
    from strandly.serve.deploy import CDK_ENV_CONTEXT

    return list(CDK_ENV_CONTEXT)

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="strands-factory", description="Deploy, operate and talk to a Strands Factory deployment.")
    sub = parser.add_subparsers(dest="command", required=True)

    p_chat = client.add_chat_parser(sub)
    p_chat.add_argument(
        "--agentcore",
        action="store_true",
        help="stream from the deployed AgentCore runtime over SigV4 instead of the dashboard API",
    )

    p_serve = sub.add_parser("serve", help="serve the agent")
    p_serve.add_argument("mode", choices=["agentcore", "mcp"], help="serving surface")
    p_serve.add_argument(
        "--agentcore",
        action="store_true",
        help="mcp mode only: proxy to the deployed runtime over SigV4 instead of the dashboard API",
    )
    p_serve.add_argument("--runtime-arn", help="deployed runtime ARN (else resolved automatically)")
    p_serve.add_argument("--region", help="AWS region (else resolved automatically)")

    p_login = sub.add_parser(
        "login", help="browser sign-in (Cognito PKCE) for the default `serve mcp` transport"
    )
    p_login.add_argument(
        "--portal-url",
        help="the deployed Maintainer Portal URL — discovers --api-url/--cognito-domain/--client-id "
        "from its public config.json (easiest first-time setup)",
    )
    p_login.add_argument("--api-url", help="the dashboard HTTP API endpoint (else $STRANDLY_API_URL / cached)")
    p_login.add_argument(
        "--cognito-domain",
        help="the Cognito Hosted-UI domain, https://…amazoncognito.com (else $STRANDLY_COGNITO_DOMAIN / cached)",
    )
    p_login.add_argument(
        "--client-id", help="the Cognito public app-client id (else $STRANDLY_COGNITO_CLIENT_ID / cached)"
    )

    sub.add_parser("logout", help="drop (and best-effort revoke) the cached `strands-factory login` session")

    sub.add_parser("acp", help="remote ACP agent over stdio (uses strands-factory login; install strands-factory[acp])")
    client.add_mcp_parser(sub)
    client.add_whoami_parser(sub)
    client.add_identity_parser(sub)
    client.add_sessions_parser(sub)
    client.add_build_parser(sub)

    p_prov = sub.add_parser(
        "provision", help="create the secret + AgentCore backends (drives the infra/ CDK app)"
    )
    p_prov.add_argument("--name", default="strandly", help="resource name prefix")
    p_prov.add_argument(
        "--env", default="dev", help="environment suffix isolating this deployment (dev/prod/…)"
    )
    p_prov.add_argument("--region", help="AWS region (else ambient)")
    p_prov.add_argument("--account", help="AWS account id (else resolved from credentials)")
    p_prov.add_argument(
        "--skip-sandbox",
        action="store_true",
        help=(
            "leave the deployed Sandbox stack untouched (deploy only Data + Backend) and read its "
            "runtime ARN and session-TTL outputs from the deployed stack instead"
        ),
    )
    p_prov.add_argument(
        "--github-token",
        metavar="TOKEN",
        help=(
            "store a GitHub token as STRANDLY_GITHUB_TOKEN in the config secret after the deploy "
            "(enables the use_github tool for the deployed agent). It goes straight to Secrets "
            'Manager, never into the CloudFormation template. Pass it explicitly, e.g. '
            '--github-token="$STRANDLY_GITHUB_TOKEN", so you control exactly which token is stored.'
        ),
    )

    p_deploy = sub.add_parser(
        "deploy",
        help="deploy the agent runtime: cdk deploy of the AgentRuntime stack (AgentCore microVM)",
    )
    p_deploy.add_argument(
        "--stage",
        required=True,
        help="the deployment environment (dev/prod/…), as for provision --env",
    )
    p_deploy.add_argument(
        "--name", "--app-name", dest="app_name", default="strandly", help="the CDK app name"
    )
    p_deploy.add_argument("--region", help="AWS region (else AWS_REGION / ambient)")
    p_deploy.add_argument(
        "--env",
        action="append",
        default=[],
        metavar="KEY=VALUE",
        # Generated from the stack's key map, so a new key (e.g. the sandbox TTL wiring) is listed.
        help="a backend id (repeatable): "
        + ", ".join(_deploy_env_keys())
        + ". Default: the process env, else the Backend/Sandbox stack outputs",
    )

    p_invoke = sub.add_parser(
        "invoke", help="invoke the deployed runtime (works from any folder, unlike agentcore invoke)"
    )
    p_invoke.add_argument("prompt", help="the prompt / task for the deployed agent")
    p_invoke.add_argument(
        "--session-id",
        "-s",
        help="runtime session id (affinity; 33-256 chars). Default: the canonical GitHub-item id "
        "derived from $GITHUB_CONTEXT (gh-<owner>-<repo>-<h8>-<kind>-<n>), else an ephemeral per-run id.",
    )
    p_invoke.add_argument("--runtime-arn", help="deployed runtime ARN (else resolved automatically)")
    p_invoke.add_argument("--region", help="AWS region (else resolved automatically)")
    p_invoke.add_argument(
        "--mode",
        help="portal role of the turn (draft|curate|post) — recorded on the run ledger (CONTRACT §5).",
    )
    p_invoke.add_argument(
        "--trigger-source",
        dest="trigger_source",
        help="how the run started (e.g. event:pull_request.opened, portal:curate) — ledger provenance.",
    )

    p_people = sub.add_parser(
        "people", help="edit the people directory (the DynamoDB-backed ingress allow-list)"
    )
    p_people.add_argument(
        "--table",
        help="the people table name (default: $STRANDLY_PEOPLE_TABLE, e.g. strandly-prod-people)",
    )
    p_people.add_argument("--region", help="AWS region (else resolved automatically)")
    p_people.add_argument(
        "--user-pool-id",
        help="the portal's Cognito user pool that `add --cognito` looks the user up in (default: "
        "$STRANDLY_COGNITO_USER_POOL_ID, else --dashboard-stack's CognitoUserPoolId output)",
    )
    p_people.add_argument(
        "--dashboard-stack", help="the Dashboard stack (e.g. Strandly-Dashboard-prod) to read the pool id from"
    )
    people_sub = p_people.add_subparsers(dest="people_command", required=True)
    people_sub.add_parser("list", help="print every person")
    p_add = people_sub.add_parser("add", help="add or replace a person (needs ≥1 identity)")
    p_add.add_argument("person_id", help="stable slug for the person, e.g. example-maintainer")
    p_add.add_argument("--name", default="", help='display name, e.g. "Example Maintainer"')
    p_add.add_argument("--role", default="", help="e.g. maintainer")
    p_add.add_argument("--github", default="", help="GitHub login (case-insensitive)")
    p_add.add_argument("--slack", default="", help="Slack user id, e.g. U0123ABC")
    bind = p_add.add_mutually_exclusive_group()
    bind.add_argument(
        "--cognito", default="", help="bind the portal user with this Cognito username or email"
    )
    bind.add_argument("--cognito-sub", default="", help="bind the portal user with this Cognito sub")
    bind.add_argument(
        "--unbind-cognito",
        action="store_true",
        help="drop the row's portal-user binding (without a --cognito* flag, a replaced row keeps it)",
    )
    p_add.add_argument(
        "--disabled", action="store_true", help="store the row but let it authorize nothing"
    )
    p_remove = people_sub.add_parser("remove", help="delete a person")
    p_remove.add_argument("person_id")

    p_poll = sub.add_parser("poll", help="poll a deployed run for its status/result")
    p_poll.add_argument("task_id", help="the taskId returned when the run was launched")
    p_poll.add_argument(
        "--session-id", "-s", help="the run's session id (affinity). Default: same derivation as invoke."
    )
    p_poll.add_argument("--runtime-arn", help="deployed runtime ARN (else resolved automatically)")
    p_poll.add_argument("--region", help="AWS region (else resolved automatically)")

    return parser


def _parse_env(pairs: list[str]) -> dict[str, str]:
    """Parse ``KEY=VALUE`` strings from repeated --env flags."""
    out: dict[str, str] = {}
    for p in pairs:
        key, sep, value = p.partition("=")
        if not sep:
            raise SystemExit(f"--env expects KEY=VALUE, got: {p!r}")
        out[key.strip()] = value
    return out


def _people_command(args: argparse.Namespace) -> int:
    """``strandly people {list,add,remove}`` — the operator path into the people directory.

    Runs with the operator's own AWS credentials against the table by name; the deployed agent has
    no grant on this table (see ``ops/people.py``), which is the point — editing who may trigger
    Strandly is a human action, never something the agent can do for itself.
    """
    import json
    import os

    import boto3

    from strandly.ops import people
    from strandly.serve.deploy import resolve_region

    table = args.table or os.environ.get(people.PEOPLE_TABLE_ENV)
    if not table:
        print("people: no table (pass --table or set STRANDLY_PEOPLE_TABLE)", file=sys.stderr)
        return 1
    region = resolve_region(args.region)
    client = boto3.client("dynamodb", region_name=region)

    if args.people_command == "list":
        rows = [vars(p) for p in people.list_people(client, table)]
        print(json.dumps(rows, indent=2))
        return 0
    if args.people_command == "add":
        try:
            if args.unbind_cognito:
                cognito_sub = ""
            elif args.cognito_sub or args.cognito:
                cognito_sub = args.cognito_sub or _resolve_cognito_sub(args, region, args.cognito)
            else:
                # Replacing a row keeps its portal-user binding, as the people-admin UI does: an
                # edit of a name or role must not silently move a person's portal runs to team memory.
                cognito_sub = _stored_cognito_sub(client, table, args.person_id)
            stored = people.upsert_person(
                client,
                table,
                people.Person(
                    person_id=args.person_id,
                    name=args.name,
                    role=args.role,
                    github_login=args.github,
                    slack_user_id=args.slack,
                    enabled=not args.disabled,
                    cognito_sub=cognito_sub,
                ),
            )
        except ValueError as e:
            print(f"people add: {e}", file=sys.stderr)
            return 1
        print(json.dumps(vars(stored), indent=2))
        return 0
    people.remove_person(client, table, args.person_id)
    print(f"removed {args.person_id}")
    return 0


def _stored_cognito_sub(client: Any, table: str, person_id: str) -> str:
    """The portal user the existing row ``person_id`` is bound to, or ``""``."""
    got = client.get_item(
        TableName=table, Key={"person_id": {"S": person_id.strip().lower()}}, ConsistentRead=True
    )
    value = (got.get("Item") or {}).get("cognito_sub", {}).get("S")
    return value if isinstance(value, str) else ""


def _resolve_cognito_sub(args: argparse.Namespace, region: str | None, username: str) -> str:
    """The ``sub`` of portal user ``username`` in the deployment's pool (``ValueError`` if unknown)."""
    import os

    import boto3

    from strandly.ops import people
    from strandly.serve.provisioning import deployed_stack_outputs

    pool = args.user_pool_id or os.environ.get("STRANDLY_COGNITO_USER_POOL_ID", "")
    if not pool and args.dashboard_stack:
        pool = (deployed_stack_outputs(args.dashboard_stack, region) or {}).get("CognitoUserPoolId", "")
    if not pool:
        raise ValueError(
            "--cognito needs the user pool: pass --user-pool-id or --dashboard-stack, or set "
            "STRANDLY_COGNITO_USER_POOL_ID"
        )
    client = boto3.client("cognito-idp", region_name=region)
    try:
        return people.cognito_sub_of(client, pool, username)
    except Exception as e:  # botocore ClientError, matched by code
        if (getattr(e, "response", None) or {}).get("Error", {}).get("Code") == "UserNotFoundException":
            raise ValueError(f"no Cognito user {username!r} in {pool}") from e
        raise


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    _quiet_noisy_loggers()

    if args.command == "acp":
        try:
            from strandly_cli.acp import main as acp_main
        except ImportError:
            print("ACP requires the optional dependencies: install strands-factory[acp]", file=sys.stderr)
            return 1
        return acp_main()

    # The client commands are the same code a generated CLI runs (strandly_cli).
    ctx = client.ClientContext()
    if args.command == "whoami":
        return client.run_whoami(ctx)
    if args.command == "identity":
        return client.run_identity(ctx, args)
    if args.command == "sessions":
        return client.run_sessions(ctx, args)
    if args.command == "cli":
        return client.run_build(args)
    if args.command == "chat" and not args.agentcore:
        return client.run_chat(ctx, args)
    if args.command == "mcp":
        # `strandly mcp` is `strandly serve mcp` under the name every generated CLI uses.
        args.command, args.mode = "serve", "mcp"

    if args.command == "provision":
        from strandly.serve.provisioning import provision

        extra_secrets: dict[str, str] = {}
        if args.github_token:
            # Store under STRANDLY_GITHUB_TOKEN — the key the deployed agent's github gate reads.
            extra_secrets["STRANDLY_GITHUB_TOKEN"] = args.github_token

        provision(
            name=args.name,
            env=args.env,
            region=args.region,
            account=args.account,
            extra_secrets=extra_secrets or None,
            skip_sandbox=args.skip_sandbox,
        )
        return 0

    if args.command == "deploy":
        from strandly.serve.deploy import deploy_cdk, resolve_region

        region = resolve_region(args.region)
        if not region:
            print("deploy: no region (pass --region or set AWS_REGION)", file=sys.stderr)
            return 1
        return deploy_cdk(
            app_name=args.app_name, stage=args.stage, region=region, env=_parse_env(args.env)
        )

    if args.command == "invoke" and not args.prompt.strip():
        # The runtime refuses it too (400), but there is no reason to make the round trip.
        print("invoke: the prompt is empty — pass the task as the PROMPT argument", file=sys.stderr)
        return 2

    if args.command in ("invoke", "poll"):
        import json

        from strandly.serve.deploy import resolve_region, resolve_runtime_arn

        runtime_arn = resolve_runtime_arn(args.runtime_arn)
        region = resolve_region(args.region)
        if not runtime_arn:
            print(
                f"{args.command}: no runtime ARN — deploy first, pass --runtime-arn, or set "
                "STRANDLY_RUNTIME_ARN",
                file=sys.stderr,
            )
            return 1
        if not region:
            print(f"{args.command}: no region (pass --region or set AWS_REGION)", file=sys.stderr)
            return 1

        # One scoped id for every ingress: an explicit --session-id wins, else derive the
        # canonical GitHub-item id from $GITHUB_CONTEXT so an Action invoke and a mention land in
        # the same session (strandly.ops.lambdas.mention_poller.sessions).
        from strandly.ops.lambdas.mention_poller.sessions import (
            session_id_from_github_event,
        )

        session_id = args.session_id or session_id_from_github_event()
        if not args.session_id:
            print(f"{args.command}: using derived session id {session_id!r}", file=sys.stderr)

        if args.command == "invoke":
            from strandly.ops.runtime_client import launch_run

            # Fire-and-forget: no GitHub context required. Returns a taskId to poll; the result
            # is read back from the session store under this session id by `strandly poll`.
            # --mode / --trigger-source (when given) land on the ledger as the turn's portal role +
            # provenance — this is how an event Action stamps mode=draft / trigger_source.
            result = launch_run(
                runtime_arn,
                region,
                session_id,
                args.prompt,
                mode=args.mode,
                trigger_source=args.trigger_source,
            )
        else:
            from strandly.ops.runtime_client import poll_run

            result = poll_run(runtime_arn, region, session_id, args.task_id)
        print(json.dumps(result, indent=2))
        return 0 if result.get("status") != "error" else 1

    if args.command == "people":
        return _people_command(args)

    if args.command == "login":
        from strandly_mcp.auth import login_command

        code = login_command(
            api_url=args.api_url,
            cognito_domain=args.cognito_domain,
            client_id=args.client_id,
            portal_url=args.portal_url,
        )
        if code == 0:
            client.verify_identity_after_login(client.ClientContext())
        return code

    if args.command == "logout":
        from strandly_mcp.auth import logout_command

        return logout_command()

    if args.command == "serve" and args.agentcore:
        # The deployed-runtime MCP proxy: no local Config/secrets — resolve the runtime like
        # invoke/poll and speak InvokeAgentRuntime. (serve agentcore IS the deployed entrypoint,
        # so the flag is meaningful only for mcp.)
        if args.mode != "mcp":
            print("serve: --agentcore applies to `serve mcp` only", file=sys.stderr)
            return 1
        from strandly.serve.deploy import resolve_region, resolve_runtime_arn

        runtime_arn = resolve_runtime_arn(args.runtime_arn)
        region = resolve_region(args.region)
        if not runtime_arn:
            print(
                "serve mcp --agentcore: no runtime ARN — deploy first, pass --runtime-arn, or "
                "set STRANDLY_RUNTIME_ARN",
                file=sys.stderr,
            )
            return 1
        if not region:
            print("serve mcp --agentcore: no region (pass --region or set AWS_REGION)", file=sys.stderr)
            return 1
        from strandly_mcp.server import serve_mcp_proxy

        serve_mcp_proxy(runtime_arn, region)
        return 0

    if args.command == "serve" and args.mode == "mcp":
        # The DEFAULT `serve mcp`: proxy to the deployed runtime through the dashboard API with
        # the cached Cognito session — the teammate path; no AWS credentials, no Config/secrets.
        from strandly_mcp.auth import load_auth

        auth = load_auth()
        if auth is None:
            print(
                "serve mcp: not logged in — run `strands-factory login` first "
                "(or use --agentcore for direct SigV4)",
                file=sys.stderr,
            )
            return 1
        from strandly_mcp.server import serve_mcp_dashboard_proxy

        serve_mcp_dashboard_proxy(auth)
        return 0

    if args.command == "chat":
        from strandly.serve.cli.repl import chat_agentcore
        from strandly.serve.deploy import resolve_region, resolve_runtime_arn

        runtime_arn = resolve_runtime_arn(None)
        region = resolve_region(None)
        if not runtime_arn or not region:
            print(
                "chat --agentcore needs a deployed runtime: a resolvable runtime ARN "
                "(deploy first / STRANDLY_RUNTIME_ARN) and a region.",
                file=sys.stderr,
            )
            return 1
        chat_agentcore(runtime_arn, region, args.session_id or "strandly-chat")
        return 0

    from strandly.core.config import Config
    from strandly.serve.agentcore_app import serve_agentcore

    serve_agentcore(Config.load())
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
